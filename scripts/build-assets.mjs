#!/usr/bin/env node
/**
 * Generates `src/assets.ts` — the self-hosted fonts and images the Worker serves
 * from `/font/{file}` and `/img/{file}`.
 *
 * Why self-hosted: the logos were moved off `google.com/s2/favicons` because every
 * third-party asset hands the visitor's IP and our referrer to someone else. Loading
 * the type from Google Fonts would undo that on every page, so these files ship
 * inside the Worker like the logos do.
 *
 * Sources are committed under `assets/`:
 * - `fonts/`: Geist and Geist Mono variable woff2 from the `geist` npm package 1.9.0,
 *   SIL Open Font License 1.1 (`assets/fonts/OFL.txt`). One variable file per family
 *   covers every weight the pages use.
 * - `img/`: the About page figure, filmed with stageshow from `docs/about-figure/`,
 *   one still per theme.
 *
 * Run `npm run assets` after replacing a file; `--check` verifies the committed
 * module instead of writing.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const CHECK_ONLY = process.argv.includes('--check');
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'src/assets.ts');

const FONTS = ['Geist-Variable.woff2', 'GeistMono-Variable.woff2'];
const IMAGES = ['about-dark.png', 'about-light.png'];

function embed(dir, files) {
  const hash = createHash('sha256');
  const entries = files.map((name) => {
    const bytes = readFileSync(join(ROOT, 'assets', dir, name));
    hash.update(name).update(bytes);
    return `  ${JSON.stringify(name)}: ${JSON.stringify(bytes.toString('base64'))},`;
  });
  return { entries: entries.join('\n'), version: hash.digest('hex').slice(0, 10) };
}

const fonts = embed('fonts', FONTS);
const images = embed('img', IMAGES);

const out = `// GENERATED by scripts/build-assets.mjs — do not edit. Run \`npm run assets\`.
// Fonts: Geist and Geist Mono (SIL Open Font License 1.1, assets/fonts/OFL.txt).

/** Change whenever a file does; appended as ?v= so the year-long cache can't pin a stale file. */
export const FONT_ASSET_VERSION = ${JSON.stringify(fonts.version)};
export const IMAGE_ASSET_VERSION = ${JSON.stringify(images.version)};

const FONTS: Record<string, string> = {
${fonts.entries}
};

const IMAGES: Record<string, string> = {
${images.entries}
};

function decode(table: Record<string, string>, file: string): Uint8Array<ArrayBuffer> | null {
  if (!Object.prototype.hasOwnProperty.call(table, file)) return null;
  const bin = atob(table[file]);
  const bytes = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);
  return bytes;
}

/** The woff2 bytes for a served font file, or null when there is no such font. */
export function fontBytes(file: string): Uint8Array<ArrayBuffer> | null {
  return decode(FONTS, file);
}

/** The PNG bytes for a served image file, or null when there is no such image. */
export function imageBytes(file: string): Uint8Array<ArrayBuffer> | null {
  return decode(IMAGES, file);
}
`;

if (CHECK_ONLY) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== out) {
    console.error('src/assets.ts is stale or hand-edited; run `npm run assets`.');
    process.exit(1);
  }
  console.log(`src/assets.ts ok (fonts ${fonts.version}, images ${images.version})`);
} else {
  writeFileSync(OUT, out);
  console.log(`wrote src/assets.ts (fonts ${fonts.version}, images ${images.version})`);
}
